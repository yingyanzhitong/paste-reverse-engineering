import AppKit
import Foundation

private let multiItemPayloadKey = "com.pastereplica.internal.items+json"
private let generatedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
private let replicaGeneratedType = NSPasteboard.PasteboardType("com.pastereplica.generated")
private let concealedTypes: Set<String> = ["org.nspasteboard.ConcealedType", "com.agilebits.onepassword"]
private let transientTypes: Set<String> = ["org.nspasteboard.TransientType", "de.petermaurer.TransientPasteboardType", generatedType.rawValue]

extension ClipboardStore {
    @discardableResult
    public func capture(pasteboard: NSPasteboard, sourceName: String, sourceBundleID: String?) throws -> UUID? {
        let rawItems = pasteboard.pasteboardItems ?? []
        let types = Set(rawItems.flatMap { $0.types.map(\.rawValue) })
        guard !types.isEmpty, !types.contains(replicaGeneratedType.rawValue) else { return nil }
        // Merge pending UI changes and another process's settings before applying capture policy.
        try save()
        if preferences.ignoreTransientContent && !types.isDisjoint(with: transientTypes) { return nil }
        if preferences.ignoreConcealedContent && !types.isDisjoint(with: concealedTypes) { return nil }
        if let sourceBundleID, preferences.excludedBundleIDs.contains(sourceBundleID) { return nil }
        if let until = preferences.pauseUntil {
            if until > Date() { return nil }
            preferences.pauseUntil = nil
            preferences.isMonitoringPaused = false
            try save()
        } else if preferences.isMonitoringPaused {
            return nil
        }
        var representations = rawItems.map { item -> [String: Data] in
            var values: [String: Data] = [:]
            for type in item.types where type.rawValue != multiItemPayloadKey && !Self.analysisPayloadKeys.contains(type.rawValue) {
                if let data = item.data(forType: type) { values[type.rawValue] = data }
            }
            return values
        }
        representations.removeAll(where: \.isEmpty)
        guard var payloads = representations.first else { return nil }
        if representations.count > 1 { payloads[multiItemPayloadKey] = try JSONEncoder().encode(representations) }
        let fileStrings = representations.compactMap { representation -> String? in
            guard let data = representation[NSPasteboard.PasteboardType.fileURL.rawValue],
                  let string = String(data: data, encoding: .utf8) else { return nil }
            return URL(string: string)?.path ?? string
        }
        var plainText = pasteboard.string(forType: .string) ?? pasteboard.string(forType: .URL)
        if !fileStrings.isEmpty { plainText = fileStrings.joined(separator: "\n") }
        if plainText == nil {
            for (type, documentType) in [(NSPasteboard.PasteboardType.rtf, NSAttributedString.DocumentType.rtf),
                                          (.rtfd, .rtfd)] {
                if let data = payloads[type.rawValue],
                   let rich = try? NSAttributedString(data: data, options: [.documentType: documentType], documentAttributes: nil) {
                    plainText = rich.string
                    break
                }
            }
        }
        let kind: ClipboardKind
        if types.contains(NSPasteboard.PasteboardType.fileURL.rawValue) || types.contains("NSFilenamesPboardType") {
            kind = .files
        } else if types.contains(NSPasteboard.PasteboardType.png.rawValue) || types.contains(NSPasteboard.PasteboardType.tiff.rawValue) {
            kind = .image
        } else if types.contains(NSPasteboard.PasteboardType.color.rawValue) {
            kind = .color
        } else if !types.isDisjoint(with: [NSPasteboard.PasteboardType.rtf.rawValue,
                                          NSPasteboard.PasteboardType.rtfd.rawValue,
                                          NSPasteboard.PasteboardType.html.rawValue]) {
            kind = .richText
        } else if plainText.map(Self.isLink) == true {
            kind = .link
        } else if plainText.map(Self.isColor) == true {
            kind = .color
        } else if plainText != nil {
            kind = .text
        } else {
            kind = .unknown
        }
        let title = String((plainText?.split(whereSeparator: \.isNewline).first.map(String.init) ?? kind.displayName).prefix(100))
        let id = try add(ClipboardItem(title: title, kind: kind, plainText: plainText, sourceName: sourceName,
                                       sourceBundleID: sourceBundleID, payloads: payloads))
        if kind == .image { startBackgroundTextRecognition(id: id) }
        return id
    }

    public func writeToPasteboard(id: UUID, pasteboard: NSPasteboard, plainTextOnly: Bool = false) throws {
        try writeToPasteboard(ids: [id], pasteboard: pasteboard, plainTextOnly: plainTextOnly)
    }

    public func writeToPasteboard(ids: [UUID], pasteboard: NSPasteboard, plainTextOnly: Bool = false) throws {
        try save()
        guard !ids.isEmpty else { throw ClipboardStoreError.itemNotFound }
        let selected = try ids.map { id -> ClipboardItem in
            guard let item = items.first(where: { $0.id == id && !$0.isDeleted }) else { throw ClipboardStoreError.itemNotFound }
            return item
        }
        var objects: [NSPasteboardItem] = []
        if plainTextOnly {
            let texts = try selected.map { item -> String in
                if let text = item.plainText { return text }
                if let text = item.recognizedText, !text.isEmpty { return text }
                throw ClipboardStoreError.missingPlainText
            }
            let object = NSPasteboardItem()
            object.setString(texts.joined(separator: "\n"), forType: .string)
            objects = [object]
        } else {
          for item in selected {
            let representations: [[String: Data]]
            if let data = item.payloads[multiItemPayloadKey] {
                representations = try JSONDecoder().decode([[String: Data]].self, from: data)
            } else {
                representations = [item.payloads]
            }
            for representation in representations {
                let object = NSPasteboardItem()
                for (type, data) in representation where type != multiItemPayloadKey && !Self.analysisPayloadKeys.contains(type) {
                    object.setData(data, forType: NSPasteboard.PasteboardType(type))
                }
                if object.types.isEmpty, let text = item.plainText { object.setString(text, forType: .string) }
                if !object.types.isEmpty { objects.append(object) }
            }
          }
        }
        guard let first = objects.first else { throw ClipboardStoreError.pasteboardWriteFailed }
        first.setData(Data(), forType: generatedType)
        first.setData(Data(), forType: replicaGeneratedType)
        pasteboard.clearContents()
        guard pasteboard.writeObjects(objects) else { throw ClipboardStoreError.pasteboardWriteFailed }
    }
}

@MainActor
public final class ClipboardMonitor {
    private let store: ClipboardStore
    private let pasteboard: NSPasteboard
    private var timer: Timer?
    private var lastChangeCount: Int
    public private(set) var lastError: Error?
    public var onCapture: ((UUID) -> Void)?

    public init(store: ClipboardStore, pasteboard: NSPasteboard = .general) {
        self.store = store
        self.pasteboard = pasteboard
        self.lastChangeCount = pasteboard.changeCount
    }

    public func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        if let timer { RunLoop.main.add(timer, forMode: .common) }
    }

    public func stop() {
        timer?.invalidate()
        timer = nil
    }

    public func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        let app = NSWorkspace.shared.frontmostApplication
        do {
            let captured = try store.capture(pasteboard: pasteboard, sourceName: app?.localizedName ?? "未知应用",
                                             sourceBundleID: app?.bundleIdentifier)
            if captured != nil, store.preferences.playSounds { NSSound(named: .init("Pop"))?.play() }
            if let captured { onCapture?(captured) }
            lastError = nil
        } catch {
            lastError = error
        }
    }

    deinit { timer?.invalidate() }
}
